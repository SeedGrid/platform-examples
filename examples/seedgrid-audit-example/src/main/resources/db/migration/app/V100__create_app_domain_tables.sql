-- Tabelas de dominio do app de teste de audit (customers/business_units/legacy_products).
-- O schema do AUDIT vem de db/migration/audit; aqui ficam as entidades de dominio que os
-- testes exercitam (POST/DELETE -> verificacao do audit).

-- Customer: extends BaseEntityPanache (id, public_id, created_at, updated_at,
-- create/update_user_public_id) — SEM coluna active.
CREATE TABLE IF NOT EXISTS customers (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id              VARCHAR(255) NOT NULL,
    created_at             TIMESTAMP,
    updated_at             TIMESTAMP,
    create_user_public_id  VARCHAR(255),
    update_user_public_id  VARCHAR(255),
    cpf                    VARCHAR(20)  NOT NULL,
    name                   VARCHAR(255) NOT NULL,
    occupation             VARCHAR(255),
    job                    VARCHAR(255),
    birth_date             DATE,
    address                VARCHAR(500),
    postal_code            VARCHAR(20),
    city                   VARCHAR(255),
    comment                TEXT,
    internal_code          VARCHAR(100),
    CONSTRAINT uk_customers_public_id UNIQUE (public_id),
    CONSTRAINT uk_customers_cpf       UNIQUE (cpf)
);

-- BusinessUnit: extends BaseEntity (+ active).
CREATE TABLE IF NOT EXISTS business_units (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id              VARCHAR(255) NOT NULL,
    active                 BOOLEAN NOT NULL DEFAULT TRUE,
    created_at             TIMESTAMP,
    updated_at             TIMESTAMP,
    create_user_public_id  VARCHAR(255),
    update_user_public_id  VARCHAR(255),
    code                   VARCHAR(50)  NOT NULL,
    name                   VARCHAR(255) NOT NULL,
    CONSTRAINT uk_business_units_public_id UNIQUE (public_id),
    CONSTRAINT uk_business_units_code      UNIQUE (code)
);

-- LegacyProduct: standalone (sem BaseEntity).
CREATE TABLE IF NOT EXISTS legacy_products (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_code VARCHAR(80)  NOT NULL,
    name          VARCHAR(255) NOT NULL,
    CONSTRAINT uk_legacy_products_external_code UNIQUE (external_code)
);
